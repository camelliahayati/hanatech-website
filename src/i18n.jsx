const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved === 'en' || saved === 'sv') return saved;
    return window.navigator.language.toLowerCase().startsWith('sv') ? 'sv' : 'en';
  });

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (text) => (language === 'sv' ? sv[text] ?? text : text),
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  return context;
}

export function LanguageSwitcher({ className = '' }) {
  const { language, setLanguage, t } = useLanguage();
  return (
    <div className={`language-switcher ${className}`.trim()} role="group" aria-label={t('Switch language')}>
      <button type="button" className={language === 'en' ? 'active' : ''} onClick={() => setLanguage('en')} aria-pressed={language === 'en'} aria-label={t('English')}>EN</button>
      <span aria-hidden="true">/</span>
      <button type="button" className={language === 'sv' ? 'active' : ''} onClick={() => setLanguage('sv')} aria-pressed={language === 'sv'} aria-label={t('Swedish')}>SV</button>
    </div>
  );
}
